// ========================================
// OVERLAY ELEMENTS
// ========================================

const campaignOverlay = document.getElementById("campaignOverlay");
const campaignContent = document.getElementById("campaignContent");
const campaignClose = document.getElementById("campaignClose");


// ========================================
// RENDER CAMPAIGN
// ========================================

function renderCampaign(campaign) {

    campaignContent.innerHTML = `

        <section class="campaign-hero">

            <div class="campaign-meta">
                <span>CAMPAIGN / ${campaign.number}</span>
                <span>${campaign.type}</span>
            </div>

            <p class="eyebrow">
                ${campaign.brand} · BRAND STORYTELLING
            </p>

            <h1>${campaign.name}</h1>

        </section>


        <!-- CAMPAIGN OVERVIEW -->

        <section class="campaign-overview">

            <div class="overview-label">
                <p>THE IDEA</p>
                <h3>${campaign.idea}</h3>

            </div>

            <div class="overview-content">

                <h2>
                    Theme<br>
                    <em>${campaign.theme}</em>
                </h2>

                <p class="campaign-description">
                    ${campaign.description}
                </p>

                <p class="campaign-insight">
                    ${campaign.insight}
                </p>

            </div>

        </section>


        <!-- SCRIPT -->

        <section class="campaign-script">

            <div class="section-top">
                <span>02 / THE FILM</span>
                <p>SCRIPT</p>
            </div>

            <h2>
                The story<br>
                <em>in words.</em>
            </h2>

            <div class="script-content">

                ${campaign.script.map((item, index) => `

                    <div class="script-line">

                        <span class="script-number">
                            ${String(index + 1).padStart(2, "0")}
                        </span>

                        <div>

                            <span class="script-type">
                                ${item.type}
                            </span>

                            <p>
                                ${item.content}
                            </p>

                        </div>

                    </div>

                `).join("")}

            </div>

        </section>
        <!-- CLOSING -->

        <section class="campaign-closing">

            <p>THE THOUGHT BEHIND THE FILM</p>

            <h2>
                <em>${campaign.closing}</em>
            </h2>

            <span>
                ${campaign.brand} / ${campaign.name}
            </span>

        </section>


        <!-- FOOTER -->

        <footer class="campaign-footer">

            <span>PRACHI / CREATIVE PORTFOLIO</span>

            <span>IDEAS THAT MAKE YOU FEEL.</span>

        </footer>

    `;

    // Open overlay
    campaignOverlay.classList.add("active");

    // Prevent background scrolling
    document.body.style.overflow = "hidden";

    // Start at the top of the campaign
    campaignContent.scrollTop = 0;
}


// ========================================
// OPEN CAMPAIGN
// ========================================

document.querySelectorAll(".campaign-card").forEach(card => {

    card.addEventListener("click", function(event) {

        event.preventDefault();

        const campaignId = this.dataset.campaign;

        const campaign = campaigns[campaignId];

        if (!campaign) {
            console.error("Campaign not found:", campaignId);
            return;
        }

        renderCampaign(campaign);

    });

});


// ========================================
// CLOSE CAMPAIGN
// ========================================

function closeCampaign() {

    campaignOverlay.classList.remove("active");

    document.body.style.overflow = "";

}


// Close button
campaignClose.addEventListener("click", closeCampaign);


// Escape key
document.addEventListener("keydown", function(event) {

    if (event.key === "Escape" && campaignOverlay.classList.contains("active")) {
        closeCampaign();
    }

});


// Click outside content to close (optional)
campaignOverlay.addEventListener("click", function(event) {

    if (event.target === campaignOverlay) {
        closeCampaign();
    }

});
